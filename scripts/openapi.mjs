// Keeps the API types in step with retina-server.
//
//   node scripts/openapi.mjs pull <retina-server checkout>  dump that checkout's OpenAPI, then `types`
//   node scripts/openapi.mjs types                          regenerate src/api/schema.gen.ts
//   node scripts/openapi.mjs check                          exit 1 if schema.gen.ts is out of date
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const snapshotPath = path.join(root, 'openapi', 'retina-server.json');
const sourcePath = path.join(root, 'openapi', 'source.json');
const schemaPath = path.join(root, 'src', 'api', 'schema.gen.ts');

const HEADER =
  '// Generated by `npm run api:types` from openapi/retina-server.json. Do not edit by hand.\n\n';

// Imports the app the way uvicorn would and writes the full app.openapi(), not the
// filtered public /openapi.json, so the auth routes are typed too.
const DUMP_PY = [
  'import json, sys',
  'from main import app',
  "with open(sys.argv[1], 'w', encoding='utf-8') as f:",
  '    json.dump(app.openapi(), f)',
].join('\n');

function fail(message) {
  throw new Error(message);
}

function run(command, args, options) {
  const result = spawnSync(command, args, { encoding: 'utf8', ...options });
  if (result.error) fail(`${command}: ${result.error.message}`);
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? '');
    process.stderr.write(result.stderr ?? '');
    fail(`${command} ${args[0]} exited with ${result.status ?? result.signal}`);
  }
  return result.stdout;
}

async function generate() {
  const document = JSON.parse(fs.readFileSync(snapshotPath, 'utf8'));
  const ast = await openapiTS(document, { silent: true });
  return HEADER + astToString(ast);
}

async function types() {
  const contents = await generate();
  fs.mkdirSync(path.dirname(schemaPath), { recursive: true });
  fs.writeFileSync(schemaPath, contents);
  console.log(`wrote ${path.relative(root, schemaPath)}`);
}

async function check() {
  const expected = await generate();
  const actual = fs.existsSync(schemaPath) ? fs.readFileSync(schemaPath, 'utf8') : null;
  if (actual !== expected) {
    fail(`${path.relative(root, schemaPath)} is out of date: run npm run api:types`);
  }
  console.log(`${path.relative(root, schemaPath)} is up to date`);
}

async function pull(checkoutArg) {
  if (!checkoutArg) fail('usage: npm run api:pull -- <path to a retina-server checkout>');
  const checkout = path.resolve(checkoutArg);
  const backend = path.join(checkout, 'backend');
  const python = path.join(backend, '.venv', 'bin', 'python');
  if (!fs.existsSync(python)) fail(`no virtualenv at ${python}`);

  const commit = run('git', ['-C', checkout, 'rev-parse', 'HEAD']).trim();
  // Importing the app opens its database; a throwaway one keeps the checkout untouched.
  const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'retina-openapi-'));
  let document;
  try {
    const out = path.join(tempDir, 'openapi.json');
    run(python, ['-c', DUMP_PY, out], {
      cwd: backend,
      env: { ...process.env, RETINA_ENV: 'dev', RETINA_DB_PATH: path.join(tempDir, 'retina.db') },
      timeout: 300_000,
    });
    document = JSON.parse(fs.readFileSync(out, 'utf8'));
  } finally {
    fs.rmSync(tempDir, { recursive: true, force: true });
  }

  fs.mkdirSync(path.dirname(snapshotPath), { recursive: true });
  fs.writeFileSync(snapshotPath, `${JSON.stringify(document, null, 2)}\n`);
  const source = { repository: 'offworldlabs/retina-server', commit };
  fs.writeFileSync(sourcePath, `${JSON.stringify(source, null, 2)}\n`);
  console.log(
    `wrote ${path.relative(root, snapshotPath)}: ${Object.keys(document.paths ?? {}).length} paths at ${commit}`,
  );
  await types();
}

const [command, arg] = process.argv.slice(2);
const commands = { pull: () => pull(arg), types, check };
try {
  if (!Object.hasOwn(commands, command)) {
    fail('usage: node scripts/openapi.mjs pull <checkout> | types | check');
  }
  await commands[command]();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
